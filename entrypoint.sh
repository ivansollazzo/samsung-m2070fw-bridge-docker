#!/bin/bash
# Entrypoint for samsung-m2070fw-bridge-docker
#  1. configures SANE: Samsung's own smfp backend (default) or the open-source
#     xerox_mfp backend, to reach the printer over the network
#  2. makes sure an avahi-daemon is reachable (host's, or one started here)
#  3. runs AirSane, which publishes the scanner as an AirScan/eSCL device
set -euo pipefail

log() { echo "[bridge] $*"; }
die() { echo "[bridge] ERROR: $*" >&2; exit 1; }

: "${SCANNER_IP:?SCANNER_IP is required (IP address or hostname of the M2070FW)}"
SCANNER_PORT="${SCANNER_PORT:-9400}"
SCANNER_LOCATION="${SCANNER_LOCATION:-}"
LISTEN_PORT="${LISTEN_PORT:-8090}"
AVAHI_MODE="${AVAHI_MODE:-auto}"
WEB_INTERFACE="${WEB_INTERFACE:-true}"
DEBUG="${DEBUG:-false}"
RESCAN_INTERVAL="${RESCAN_INTERVAL:-60}"
SCAN_BACKEND="${SCAN_BACKEND:-smfp}"
SANE_JPEG="${SANE_JPEG:-}"
DBUS_SOCKET=/run/dbus/system_bus_socket

# --- 1. SANE ---------------------------------------------------------------
# Load exactly one backend: faster discovery, no duplicate devices and no eSCL
# backends that could loop back onto AirSane itself. The Samsung packages also
# register backends in dll.d, which would bypass dll.conf, so clear it.
rm -f /etc/sane.d/dll.d/*
echo "${SCAN_BACKEND}" > /etc/sane.d/dll.conf
cp /etc/airsane/ignore.conf.default /etc/airsane/ignore.conf

case "${SCAN_BACKEND}" in
  smfp)
    # Samsung Unified Linux Driver: finds network devices by itself (SNMP
    # broadcast) and names them like "smfp:net;192.168.1.50". If there are
    # other Samsung MFPs on the LAN, publish only the one at SCANNER_IP.
    if [[ "${SCANNER_IP}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
      ip_re="${SCANNER_IP//./\\.}"
      echo "smfp:(?!.*${ip_re}([^0-9]|$)).*" >> /etc/airsane/ignore.conf
    fi
    log "SANE: smfp (Samsung ULD), auto-discovery; publishing ${SCANNER_IP}"
    ;;
  xerox_mfp)
    printf '%s\n' "# Generated by entrypoint.sh: Samsung Xpress M2070FW over the network" \
      "tcp ${SCANNER_IP} ${SCANNER_PORT}" > /etc/sane.d/xerox_mfp.conf
    log "SANE: xerox_mfp -> tcp ${SCANNER_IP}:${SCANNER_PORT}"
    ;;
  *) die "SCAN_BACKEND must be smfp or xerox_mfp (got '${SCAN_BACKEND}')" ;;
esac

# --- 2. AirSane options ------------------------------------------------------
# A user-supplied file mounted at /config/options.conf takes precedence.
if [[ -f /config/options.conf ]]; then
  cp /config/options.conf /etc/airsane/options.conf
  log "AirSane: using /config/options.conf"
else
  {
    echo "# Generated by entrypoint.sh"
    echo "icon Gnome-scanner.png"
    # macOS applies a 1.8 gamma to eSCL scans; compensate (see AirSane README)
    echo "gray-gamma 0.555555"
    echo "color-gamma 0.555555"
    # xerox_mfp only: override its "jpeg" option (unset = backend default, yes).
    # With "yes" its colour scans of the M2070FW can fail ("Not a JPEG file").
    if [[ "${SCAN_BACKEND}" == "xerox_mfp" && -n "${SANE_JPEG}" ]]; then
      echo "jpeg ${SANE_JPEG}"
    fi
    if [[ -n "${SCANNER_LOCATION}" ]]; then echo "location ${SCANNER_LOCATION}"; fi
  } > /etc/airsane/options.conf
fi
if [[ -f /config/access.conf ]]; then
  cp /config/access.conf /etc/airsane/access.conf
  log "AirSane: using /config/access.conf"
fi

# --- 3. mDNS (avahi) -------------------------------------------------------
if [[ "${AVAHI_MODE}" == "auto" ]]; then
  if [[ -S "${DBUS_SOCKET}" ]]; then AVAHI_MODE=host; else AVAHI_MODE=internal; fi
fi

case "${AVAHI_MODE}" in
  host)
    [[ -S "${DBUS_SOCKET}" ]] || die "AVAHI_MODE=host but ${DBUS_SOCKET} is not mounted"
    log "mDNS: using the host's avahi-daemon via D-Bus"
    ;;
  internal)
    log "mDNS: starting dbus + avahi-daemon inside the container"
    mkdir -p /run/dbus /run/avahi-daemon
    rm -f /run/dbus/pid /run/avahi-daemon/pid "${DBUS_SOCKET}"
    dbus-daemon --system --fork
    avahi-daemon --daemonize --no-chroot \
      || die "avahi-daemon failed to start (another mDNS responder on the host? use AVAHI_MODE=host)"
    ;;
  none)
    log "mDNS: disabled (scanner will only be reachable via http://<host>:${LISTEN_PORT}/)"
    ;;
  *) die "AVAHI_MODE must be auto, host, internal or none (got '${AVAHI_MODE}')" ;;
esac

# --- 4. Pre-flight check -------------------------------------------------------
log "Looking for the scanner..."
if scan_list="$(timeout 30 scanimage -L 2>&1)" && grep -q "${SCAN_BACKEND}:" <<<"${scan_list}"; then
  log "Found: ${scan_list}"
else
  log "WARNING: scanner not found yet (is the printer on and reachable at ${SCANNER_IP}?)."
  log "         scanimage said: ${scan_list:-<nothing>}"
  log "         AirSane will start anyway and retry when the network changes or on restart."
fi

# --- 5. Printer watcher --------------------------------------------------------
# AirSane only enumerates scanners at startup, on network changes and on SIGHUP.
# If the printer was off (or rebooted), send SIGHUP when it becomes reachable
# again so the scanner (re)appears without restarting the container.
# $$ stays the same PID after `exec`, so it will be airsaned's PID.
printer_up() { timeout 3 bash -c "exec 3<>/dev/tcp/${SCANNER_IP}/${SCANNER_PORT}" 2>/dev/null; }

if [[ "${RESCAN_INTERVAL}" -gt 0 ]]; then
  (
    main_pid=$$
    if printer_up; then was_up=1; else was_up=0; fi
    while sleep "${RESCAN_INTERVAL}"; do
      kill -0 "${main_pid}" 2>/dev/null || exit 0
      if printer_up; then
        if [[ ${was_up} -eq 0 ]]; then
          log "Printer is reachable again: asking AirSane to rescan"
          kill -HUP "${main_pid}" 2>/dev/null || true
        fi
        was_up=1
      else
        if [[ ${was_up} -eq 1 ]]; then log "Printer is no longer reachable"; fi
        was_up=0
      fi
    done
  ) &
fi

# --- 6. Run AirSane --------------------------------------------------------
MDNS_ANNOUNCE=true
if [[ "${AVAHI_MODE}" == "none" ]]; then MDNS_ANNOUNCE=false; fi

log "Starting AirSane on port ${LISTEN_PORT}"
exec airsaned \
  --listen-port="${LISTEN_PORT}" \
  --access-log=- \
  --hotplug=false \
  --network-hotplug=true \
  --mdns-announce="${MDNS_ANNOUNCE}" \
  --web-interface="${WEB_INTERFACE}" \
  --local-scanners-only=false \
  --options-file=/etc/airsane/options.conf \
  --ignore-list=/etc/airsane/ignore.conf \
  --access-file=/etc/airsane/access.conf \
  --debug="${DEBUG}"

#!/bin/bash
# Entrypoint for samsung-m2070fw-bridge-docker
#  1. configures SANE: Samsung's own smfp backend (default) or the open-source
#     xerox_mfp backend, to reach the printer over the network
#  2. makes sure an avahi-daemon is reachable (host's, or one started here)
#  3. optionally runs CUPS with the Samsung driver as a shared AirPrint queue
#  4. runs AirSane, which publishes the scanner as an AirScan/eSCL device
# Scanner and printer are announced with the same name and UUID, so macOS
# shows them as one multifunction device.
set -euo pipefail

log() { echo "[bridge] $*"; }
die() { echo "[bridge] ERROR: $*" >&2; exit 1; }

: "${SCANNER_IP:?SCANNER_IP is required (IP address or hostname of the M2070FW)}"
SCANNER_PORT="${SCANNER_PORT:-9400}"
SCANNER_LOCATION="${SCANNER_LOCATION:-}"
DEVICE_NAME="${DEVICE_NAME:-Samsung SL-M2070FW}"
DEVICE_UUID="${DEVICE_UUID:-}"
LISTEN_PORT="${LISTEN_PORT:-8090}"
AVAHI_MODE="${AVAHI_MODE:-auto}"
WEB_INTERFACE="${WEB_INTERFACE:-true}"
DEBUG="${DEBUG:-false}"
RESCAN_INTERVAL="${RESCAN_INTERVAL:-60}"
SCAN_BACKEND="${SCAN_BACKEND:-smfp}"
SCAN_GAMMA="${SCAN_GAMMA:-1.0}"
SANE_JPEG="${SANE_JPEG:-}"
PRINTER_ENABLED="${PRINTER_ENABLED:-true}"
PRINTER_QUEUE="${PRINTER_QUEUE:-Samsung_SL-M2070FW}"
PRINTER_URI="${PRINTER_URI:-socket://${SCANNER_IP}:9100}"
PRINTER_PAPER="${PRINTER_PAPER:-A4}"
PRINTER_PPD="${PRINTER_PPD:-/usr/share/ppd/suld/Samsung_M2070_Series.ppd.gz}"
CUPS_PORT="${CUPS_PORT:-631}"
DBUS_SOCKET=/run/dbus/system_bus_socket

# Run a command forever, restarting it if it exits (cupsd, avahi-publish).
supervise() {
  local what="$1"; shift
  ( while true; do
      "$@" || true
      log "${what} exited, restarting in 5s"
      sleep 5
    done ) &
}

# Stable, name-based UUID (same value on every restart, so macOS does not see
# a "new" device each time the container starts).
stable_uuid() {
  local h
  h="$(printf '%s' "$1" | md5sum | cut -c1-32)"
  printf '%s-%s-3%s-%x%s-%s\n' "${h:0:8}" "${h:8:4}" "${h:13:3}" \
    $(( (0x${h:16:1} & 0x3) | 0x8 )) "${h:17:3}" "${h:20:12}"
}
if [[ -z "${DEVICE_UUID}" ]]; then
  DEVICE_UUID="$(stable_uuid "samsung-m2070fw-bridge|${DEVICE_NAME}|${SCANNER_IP}")"
fi
log "Device: '${DEVICE_NAME}' (uuid ${DEVICE_UUID})"

# --- 1. SANE ---------------------------------------------------------------
# Load exactly one backend: faster discovery, no duplicate devices and no eSCL
# backends that could loop back onto AirSane itself. The Samsung packages also
# register backends in dll.d, which would bypass dll.conf, so clear it.
rm -f /etc/sane.d/dll.d/*
echo "${SCAN_BACKEND}" > /etc/sane.d/dll.conf
cp /etc/airsane/ignore.conf.default /etc/airsane/ignore.conf

case "${SCAN_BACKEND}" in
  smfp)
    # Samsung Unified Linux Driver: finds network devices by itself (SNMP
    # broadcast) and names them like "smfp:net;192.168.1.50". If there are
    # other Samsung MFPs on the LAN, publish only the one at SCANNER_IP.
    if [[ "${SCANNER_IP}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
      ip_re="${SCANNER_IP//./\\.}"
      echo "smfp:(?!.*${ip_re}([^0-9]|$)).*" >> /etc/airsane/ignore.conf
    fi
    log "SANE: smfp (Samsung ULD), auto-discovery; publishing ${SCANNER_IP}"
    ;;
  xerox_mfp)
    printf '%s\n' "# Generated by entrypoint.sh: Samsung Xpress M2070FW over the network" \
      "tcp ${SCANNER_IP} ${SCANNER_PORT}" > /etc/sane.d/xerox_mfp.conf
    log "SANE: xerox_mfp -> tcp ${SCANNER_IP}:${SCANNER_PORT}"
    ;;
  *) die "SCAN_BACKEND must be smfp or xerox_mfp (got '${SCAN_BACKEND}')" ;;
esac

# --- 2. AirSane options ------------------------------------------------------
{
  echo "# Generated by entrypoint.sh"
  # Identity (patched AirSane): same name/UUID as the print queue
  echo "name ${DEVICE_NAME}"
  echo "make-and-model ${DEVICE_NAME}"
  echo "uuid ${DEVICE_UUID}"
  if [[ -f /config/options.conf ]]; then
    # A user-supplied file is appended, so its lines win.
    echo "# --- /config/options.conf ---"
    cat /config/options.conf
  else
    echo "icon Gnome-scanner.png"
    # 1.0 = no correction. AirSane's README suggests 0.555555 for macOS, but
    # with the M2070FW that washes text out to grey.
    echo "gray-gamma ${SCAN_GAMMA}"
    echo "color-gamma ${SCAN_GAMMA}"
    # xerox_mfp only: override its "jpeg" option (unset = backend default, yes).
    if [[ "${SCAN_BACKEND}" == "xerox_mfp" && -n "${SANE_JPEG}" ]]; then
      echo "jpeg ${SANE_JPEG}"
    fi
    if [[ -n "${SCANNER_LOCATION}" ]]; then echo "location ${SCANNER_LOCATION}"; fi
  fi
} > /etc/airsane/options.conf
if [[ -f /config/options.conf ]]; then log "AirSane: using /config/options.conf"; fi
if [[ -f /config/access.conf ]]; then
  cp /config/access.conf /etc/airsane/access.conf
  log "AirSane: using /config/access.conf"
fi

# --- 3. mDNS (avahi) -------------------------------------------------------
if [[ "${AVAHI_MODE}" == "auto" ]]; then
  if [[ -S "${DBUS_SOCKET}" ]]; then AVAHI_MODE=host; else AVAHI_MODE=internal; fi
fi

case "${AVAHI_MODE}" in
  host)
    [[ -S "${DBUS_SOCKET}" ]] || die "AVAHI_MODE=host but ${DBUS_SOCKET} is not mounted"
    log "mDNS: using the host's avahi-daemon via D-Bus"
    ;;
  internal)
    log "mDNS: starting dbus + avahi-daemon inside the container"
    mkdir -p /run/dbus /run/avahi-daemon
    rm -f /run/dbus/pid /run/avahi-daemon/pid "${DBUS_SOCKET}"
    dbus-daemon --system --fork
    avahi-daemon --daemonize --no-chroot \
      || die "avahi-daemon failed to start (another mDNS responder on the host? use AVAHI_MODE=host)"
    ;;
  none)
    log "mDNS: disabled (scanner will only be reachable via http://<host>:${LISTEN_PORT}/)"
    ;;
  *) die "AVAHI_MODE must be auto, host, internal or none (got '${AVAHI_MODE}')" ;;
esac

# --- 4. Printer (CUPS + Samsung driver) ---------------------------------------
setup_printer() {
  [[ "${PRINTER_QUEUE}" =~ ^[A-Za-z0-9_-]+$ ]] \
    || die "PRINTER_QUEUE may only contain letters, digits, _ and - (got '${PRINTER_QUEUE}')"
  [[ -f "${PRINTER_PPD}" ]] || die "PPD not found: ${PRINTER_PPD}"

  mkdir -p /etc/cups/ppd /run/cups
  sed "s/@CUPS_PORT@/${CUPS_PORT}/" /etc/cups/cupsd.conf.template > /etc/cups/cupsd.conf

  # Samsung PPD, renamed to DEVICE_NAME and defaulting to PRINTER_PAPER
  zcat -f "${PRINTER_PPD}" | sed \
    -e "s|^\*NickName:.*|*NickName: \"${DEVICE_NAME}\"|" \
    -e "s|^\*ModelName:.*|*ModelName: \"${DEVICE_NAME}\"|" \
    -e "s#^\*Default\(PageSize\|PageRegion\|ImageableArea\|PaperDimension\):.*#*Default\1: ${PRINTER_PAPER}#" \
    > "/etc/cups/ppd/${PRINTER_QUEUE}.ppd"

  # Queue written directly (instead of lpadmin) to keep a fixed UUID
  cat > /etc/cups/printers.conf <<EOF
# Generated by entrypoint.sh
<DefaultPrinter ${PRINTER_QUEUE}>
UUID urn:uuid:${DEVICE_UUID}
Info ${DEVICE_NAME}
Location ${SCANNER_LOCATION}
MakeModel ${DEVICE_NAME}
DeviceURI ${PRINTER_URI}
State Idle
StateTime $(date +%s)
Accepting Yes
Shared Yes
JobSheets none none
QuotaPeriod 0
PageLimit 0
KLimit 0
OpPolicy default
ErrorPolicy retry-job
</DefaultPrinter>
EOF
  chmod 600 /etc/cups/printers.conf

  supervise cupsd cupsd -f
  log "CUPS: queue '${PRINTER_QUEUE}' -> ${PRINTER_URI} on port ${CUPS_PORT}"

  # CUPS always announces "<name> @ <host>": announce the queue ourselves with
  # the exact device name and the same TXT keys CUPS would use: AirPrint
  # (_universal subtype + URF) for Apple, "mopria-certified" for the Windows
  # IPP class driver and Android, plain IPP for Linux (driverless printing).
  if [[ "${AVAHI_MODE}" != "none" ]]; then
    local host; host="$(hostname)"
    supervise avahi-publish avahi-publish -s \
      --subtype="_universal._sub._ipp._tcp" \
      "${DEVICE_NAME}" _ipp._tcp "${CUPS_PORT}" \
      "txtvers=1" "qtotal=1" \
      "rp=printers/${PRINTER_QUEUE}" \
      "ty=${DEVICE_NAME}" \
      "product=(${DEVICE_NAME})" \
      "note=${SCANNER_LOCATION}" \
      "adminurl=http://${host}.local:${CUPS_PORT}/printers/${PRINTER_QUEUE}" \
      "priority=0" \
      "pdl=application/pdf,application/postscript,image/jpeg,image/png,image/pwg-raster,image/urf" \
      "URF=V1.4,CP1,W8,PQ4,RS600,FN3" \
      "UUID=${DEVICE_UUID}" \
      "Color=F" "Duplex=F" "Copies=T" \
      "TLS=1.2" \
      "mopria-certified=1.3" \
      "printer-type=0x1046"
    log "mDNS: printer announced as '${DEVICE_NAME}'"
  fi
}

if [[ "${PRINTER_ENABLED}" == "true" ]]; then
  if (exec 3<>"/dev/tcp/127.0.0.1/${CUPS_PORT}") 2>/dev/null; then
    log "WARNING: port ${CUPS_PORT} is already in use on this host (CUPS running on the host?)."
    log "         Printer sharing disabled: stop the host's CUPS or set CUPS_PORT to a free port."
  else
    setup_printer
  fi
else
  log "Printer sharing disabled (PRINTER_ENABLED=${PRINTER_ENABLED})"
fi

# --- 5. Pre-flight check -------------------------------------------------------
log "Looking for the scanner..."
if scan_list="$(timeout 30 scanimage -L 2>&1)" && grep -q "${SCAN_BACKEND}:" <<<"${scan_list}"; then
  log "Found: ${scan_list}"
else
  log "WARNING: scanner not found yet (is the printer on and reachable at ${SCANNER_IP}?)."
  log "         scanimage said: ${scan_list:-<nothing>}"
  log "         AirSane will start anyway and retry when the network changes or on restart."
fi

# --- 6. Printer watcher --------------------------------------------------------
# AirSane only enumerates scanners at startup, on network changes and on SIGHUP.
# If the printer was off (or rebooted), send SIGHUP when it becomes reachable
# again so the scanner (re)appears without restarting the container.
# $$ stays the same PID after `exec`, so it will be airsaned's PID.
printer_up() { timeout 3 bash -c "exec 3<>/dev/tcp/${SCANNER_IP}/${SCANNER_PORT}" 2>/dev/null; }

if [[ "${RESCAN_INTERVAL}" -gt 0 ]]; then
  (
    main_pid=$$
    if printer_up; then was_up=1; else was_up=0; fi
    while sleep "${RESCAN_INTERVAL}"; do
      kill -0 "${main_pid}" 2>/dev/null || exit 0
      if printer_up; then
        if [[ ${was_up} -eq 0 ]]; then
          log "Printer is reachable again: asking AirSane to rescan"
          kill -HUP "${main_pid}" 2>/dev/null || true
        fi
        was_up=1
      else
        if [[ ${was_up} -eq 1 ]]; then log "Printer is no longer reachable"; fi
        was_up=0
      fi
    done
  ) &
fi

# --- 7. Run AirSane --------------------------------------------------------
MDNS_ANNOUNCE=true
if [[ "${AVAHI_MODE}" == "none" ]]; then MDNS_ANNOUNCE=false; fi

log "Starting AirSane on port ${LISTEN_PORT}"
exec airsaned \
  --listen-port="${LISTEN_PORT}" \
  --access-log=- \
  --hotplug=false \
  --network-hotplug=true \
  --mdns-announce="${MDNS_ANNOUNCE}" \
  --web-interface="${WEB_INTERFACE}" \
  --local-scanners-only=false \
  --options-file=/etc/airsane/options.conf \
  --ignore-list=/etc/airsane/ignore.conf \
  --access-file=/etc/airsane/access.conf \
  --debug="${DEBUG}"
